// Regenerates the preview-page section of THIRD_PARTY_LICENSES.
//
//   cd web && bun run licenses
//
// Walks the production dependency trees of web/package.json's `dependencies`
// through web/node_modules (so install first: `cd web && bun install`), and
// for every package, de-duplicated by name@version and sorted, writes its name,
// version, license id and full license text between the two markers in
// THIRD_PARTY_LICENSES, replacing whatever was there. Everything above the
// start marker is hand-kept and left alone.
//
// mermaid's browser build (mermaid.min.js) inlines mermaid's own dependencies,
// so walking mermaid's tree covers what it ships.
import { existsSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const webDir = join(root, "web");
const outFile = join(root, "THIRD_PARTY_LICENSES");

const START = "==== Preview page (generated by: cd web && bun run licenses) ====";
const END = "==== End of preview page ====";

type Manifest = {
  name: string;
  version: string;
  license?: string | { type?: string };
  repository?: string | { url?: string };
  homepage?: string;
  licenses?: { type?: string }[];
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
};

type Pkg = { manifest: Manifest; dir: string };

// Node-style resolution from a package's real path, so bun's isolated
// node_modules layout (symlinks into node_modules/.bun/...) works.
function resolvePackage(name: string, fromDir: string): string | null {
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const candidates = [join(dir, "node_modules", name)];
    if (basename(dir) === "node_modules") candidates.push(join(dir, name));
    for (const candidate of candidates) {
      if (existsSync(join(candidate, "package.json"))) return realpathSync(candidate);
    }
    if (dirname(dir) === dir) return null;
  }
}

function readManifest(dir: string): Manifest {
  return JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
}

function licenseId(m: Manifest): string {
  if (typeof m.license === "string") return m.license;
  if (m.license?.type) return m.license.type;
  const list = m.licenses?.map((l) => l.type).filter(Boolean);
  return list?.length ? list.join(" OR ") : "UNKNOWN";
}

// For packages offered under a choice of licenses, the one scwrote uses.
const licenseChoice: Record<string, string> = {
  elkjs: "EPL-2.0",
  dompurify: "Apache-2.0",
};

// package.json's `repository` as a browsable URL ("github:a/b", "a/b",
// "git+https://...git", "git://...", "git@host:a/b" all become https URLs).
function sourceUrl(m: Manifest): string {
  const raw = typeof m.repository === "string" ? m.repository : m.repository?.url;
  if (!raw) return m.homepage ?? "(no repository listed in package.json)";
  let url = raw.trim().replace(/^git\+/, "");
  const shorthand = url.match(/^(github|gitlab|bitbucket):(.+)$/);
  if (shorthand) url = `https://${shorthand[1]}.${shorthand[1] === "bitbucket" ? "org" : "com"}/${shorthand[2]}`;
  else if (/^[\w.-]+\/[\w.-]+$/.test(url)) url = `https://github.com/${url}`;
  url = url.replace(/^git@([^:]+):/, "https://$1/").replace(/^(git|ssh):\/\/(git@)?/, "https://");
  return url.replace(/\.git$/, "").replace(/#.*$/, "");
}

function licenseText(dir: string, m: Manifest): string {
  const files = readdirSync(dir)
    .filter((f) => /^(licen[sc]e|copying)/i.test(f) && statSync(join(dir, f)).isFile())
    .sort();
  const norm = (s: string) => s.replace(/\r\n?/g, "\n").trimEnd();
  if (files.length === 0) return `(no license file shipped; package.json declares: ${licenseId(m)})`;
  if (files.length === 1) return norm(readFileSync(join(dir, files[0]), "utf8"));
  return files.map((f) => `[${f}]\n\n${norm(readFileSync(join(dir, f), "utf8"))}`).join("\n\n");
}

const web = readManifest(webDir);
const found = new Map<string, Pkg>();
const seenDirs = new Set<string>();

function walk(name: string, fromDir: string, optional: boolean) {
  const dir = resolvePackage(name, fromDir);
  if (!dir) {
    if (optional) return;
    throw new Error(`cannot find ${name} from ${fromDir}; run: cd web && bun install`);
  }
  if (seenDirs.has(dir)) return;
  seenDirs.add(dir);
  const manifest = readManifest(dir);
  found.set(`${manifest.name}@${manifest.version}`, { manifest, dir });
  for (const dep of Object.keys(manifest.dependencies ?? {})) walk(dep, dir, false);
  for (const dep of Object.keys(manifest.optionalDependencies ?? {})) walk(dep, dir, true);
}

for (const dep of Object.keys(web.dependencies ?? {})) walk(dep, webDir, false);

const sections = [...found.keys()]
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
  .map((key) => {
    const { manifest, dir } = found.get(key)!;
    const choice = licenseChoice[manifest.name];
    const source = `Source: ${sourceUrl(manifest)} (version ${manifest.version})`;
    const used = choice ? `\nUsed under ${choice}.` : "";
    return `---- ${key} (${licenseId(manifest)}) ----\n${source}${used}\n\n${licenseText(dir, manifest)}`;
  });

const generated = `${START}\n\nGenerated from web/node_modules for the packages in web/package.json's\ndependencies and everything they depend on at run time (${found.size} packages).\n\n${sections.join("\n\n")}\n\n${END}\n`;

const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
const start = current.indexOf(START);
const end = current.indexOf(END);
let next: string;
if (start >= 0 && end > start) {
  next = current.slice(0, start) + generated + current.slice(end + END.length).replace(/^\n/, "");
} else {
  next = (current.length ? current.replace(/\n*$/, "\n\n") : "") + generated;
}
writeFileSync(outFile, next);
console.log(`wrote ${found.size} packages to ${outFile}`);
